def fetch_text(raw_url):
  """
  Fetches text content from a given URL, with caching.

  This function attempts to retrieve text data from the provided URL. To improve
  efficiency, it first checks a local cache directory ('cs_110_content/text_cache').
  If the content is found in the cache, it's read from there. Otherwise, it sends a
  GET request to the URL, saves the response text to the cache, and then returns it.
  Error handling is included for network issues or failed requests.

  Parameters:
  raw_url (str): The URL from which to fetch the text content.

  Returns:
  str: The fetched text content if successful, or an empty string if an error occurs.

  Example:
  >>> url = "https://www.gutenberg.org/cache/epub/1342/pg1342.txt"
  >>> text = fetch_text(url)
  >>> len(text) > 0
  True
  """
  import requests
  from pathlib import Path
  import hashlib

  CACHE_DIR = Path("cs_110_content/text_cache")
  CACHE_DIR.mkdir(parents=True, exist_ok=True)

  def _url_to_filename(url):
    url_hash = hashlib.sha1(url.encode("utf-8")).hexdigest()[:12]
    return CACHE_DIR / f"{url_hash}.txt"

  cache_path = _url_to_filename(raw_url)

  SUCCESS_MSG = "✅ Text fetched."
  FAILURE_MSG = "❌ Failed to fetch text."
  try:
    if not cache_path.exists():
      response = requests.get(raw_url, timeout=10)
      response.raise_for_status()
      text_data = response.text
      cache_path.write_text(text_data, encoding="utf-8")
    print(SUCCESS_MSG)
    return cache_path.read_text(encoding="utf-8")

  except Exception as e:
    print(FAILURE_MSG)
    print(f"Error: {e}")
    return ""

