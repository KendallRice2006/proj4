import spacy

nlp = spacy.load('en_core_web_sm')

def word_tokenization_normalization(text):
    """
    Performs tokenization and normalization on the input text.

    This function converts the input text to lowercase, processes it using spaCy,
    and then filters out stopwords, punctuation, numbers, and words with less
    than 3 characters. It lemmatizes the remaining words.

    Parameters:
    text (str): The input text to be processed.

    Returns:
    list: A list of normalized and lemmatized words.

    Example:
    >>> sample_text = "This is a sample sentence, with numbers 123 and stopwords."
    >>> nlp = spacy.load('en_core_web_sm') # Assuming nlp is loaded
    >>> word_tokenization_normalization(sample_text)
    ['sample', 'sentence', 'number']
    """
    text = text.lower() # lowercase
    doc = nlp(text)     # loading text into model

    words_normalized = []
    for word in doc:
        if word.text != '\n' \
        and not word.is_stop \
        and not word.is_punct \
        and not word.like_num \
        and len(word.text.strip()) > 2:
            word_lemmatized = str(word.lemma_)
            words_normalized.append(word_lemmatized)

    return words_normalized

doc_tokenized = word_tokenization_normalization(pride_prejudice_text)

print(doc_tokenized)

