def print_text_stats(text):
  """
  Calculates and prints statistics about a given text.

  This function takes a string of text and calculates the total number of characters,
  lines, and words. It then prints these statistics to the console.

  Parameters:
  text (str): The input text to analyze.

  Returns:
  None

  Example:
  >>> sample_text = "Hello world.\nThis is a test."
  >>> print_text_stats(sample_text)
  Number of characters: 29
  Number of lines: 2
  Number of words: 6
  """
  num_chars = len(text)

  lines = text.splitlines()
  num_lines = len(lines)

  num_words = 0
  for line in lines:
    words_in_line = line.split()
    num_words_in_line = len(words_in_line)
    num_words += num_words_in_line

  print(f"Number of characters: {num_chars}")
  print(f"Number of lines: {num_lines}")
  print(f"Number of words: {num_words}")

