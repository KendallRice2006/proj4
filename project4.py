def get_word_counts(text):
  """
  Calculates the frequency of each word in a given text.

  This function processes a string of text, splits it into lines, and then further
  splits each line into individual words. It converts all words to lowercase and
  counts the occurrences of each unique word, storing them in a dictionary.

  Parameters:
  text (str): The input text to analyze.

  Returns:
  dict: A dictionary where keys are lowercase words and values are their counts.

  Example:
  >>> sample_text = "Hello world.\nHello there."
  >>> get_word_counts(sample_text)
  {'hello': 2, 'world.': 1, 'there.': 1}
  """
  word_counts = {}
  lines = text.splitlines()
  for line in lines:
    words = line.split()
    for word in words:
      word = word.lower()
      if word in word_counts:
        word_counts[word] += 1
      else:
        word_counts[word] = 1
  return word_counts

word_counts = get_word_counts(pride_prejudice_text)
